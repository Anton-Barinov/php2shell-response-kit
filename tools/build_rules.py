#!/usr/bin/env python3
"""
Build platform queries from the Sigma source rules in rules/sigma/.

Requires (versions used for the published output; pyparsing must be < 3.2 with pySigma 0.11):
  pip install pySigma==0.11.23 pyparsing==3.1.4 pySigma-backend-splunk==1.1.3 \
              pySigma-backend-qradar-aql==0.3.2 pySigma-backend-crowdstrike==2.0.1 \
              pySigma-backend-sentinelone==0.1.3 pySigma-backend-sentinelone-pq==0.1.5

Usage:  python3 tools/build_rules.py
Output: rules/{splunk,qradar,crowdstrike,sentinelone}/*  (+ rules/BUILD_REPORT.md)

All generated queries are UNTESTED against live platforms. Field names follow the
backends' default data models (see header of each file). Review before deploying.
"""
from __future__ import annotations

import pathlib
import re
import sys
import traceback

from sigma.collection import SigmaCollection

ROOT = pathlib.Path(__file__).resolve().parent.parent
SIGMA_DIR = ROOT / "rules" / "sigma"


def targets():
    out = []
    from sigma.backends.splunk import SplunkBackend
    from sigma.pipelines.splunk import splunk_windows_pipeline, splunk_cim_data_model
    out.append(("splunk", "spl", "Splunk SPL - Sysmon (Windows & Linux) field names as in the Sigma rule",
                lambda: SplunkBackend(), "default"))
    out.append(("splunk", "cim.spl", "Splunk SPL - CIM Endpoint data model (tstats); needs CIM-mapped EDR/Sysmon data",
                lambda: SplunkBackend(splunk_cim_data_model()), "data_model"))
    from sigma.backends.QRadarAQL import QRadarAQLBackend
    from sigma.pipelines.QRadarAQL import QRadarAQL_fields_pipeline, QRadarAQL_payload_pipeline
    out.append(("qradar", "aql", "QRadar AQL - field-based (requires Sysmon/EDR DSM custom properties)",
                lambda: QRadarAQLBackend(QRadarAQL_fields_pipeline()), "default"))
    out.append(("qradar", "payload.aql", "QRadar AQL - payload search (no custom properties needed, slower)",
                lambda: QRadarAQLBackend(QRadarAQL_payload_pipeline()), "default"))
    from sigma.backends.crowdstrike import LogScaleBackend
    from sigma.pipelines.crowdstrike import crowdstrike_falcon_pipeline
    out.append(("crowdstrike", "logscale", "CrowdStrike Falcon (Falcon LogScale / NG-SIEM / Advanced Event Search) - Falcon data model",
                lambda: LogScaleBackend(crowdstrike_falcon_pipeline()), "default"))
    from sigma.backends.sentinelone_pq import SentinelOnePQBackend
    out.append(("sentinelone", "pq", "SentinelOne PowerQuery (Singularity Data Lake / Deep Visibility PQ)",
                lambda: SentinelOnePQBackend(), "default"))
    from sigma.backends.sentinelone import SentinelOneBackend
    out.append(("sentinelone", "dv", "SentinelOne Deep Visibility query language (legacy DV)",
                lambda: SentinelOneBackend(), "default"))
    return out


def main() -> int:
    rules = sorted(SIGMA_DIR.glob("*.yml"))
    report = ["# Build report", "", "Generated from Sigma sources with pySigma. UNTESTED against live platforms.", "",
              "| Rule | Platform | Variant | Result |", "|---|---|---|---|"]
    rc = 0
    for rule_path in rules:
        coll = SigmaCollection.from_yaml(rule_path.read_text(encoding="utf-8"))
        rule = coll.rules[0]
        for platform, ext, desc, make_backend, fmt in targets():
            outdir = ROOT / "rules" / platform
            outdir.mkdir(parents=True, exist_ok=True)
            if platform == "crowdstrike" and rule.logsource.category == "file_event":
                report.append(f"| {rule_path.stem} | {platform} | {ext} | skipped: the Falcon pipeline does not map file_event fields - use Falcon's built-in webshell/script-write detections |")
                continue
            try:
                backend = make_backend()
                queries = backend.convert(SigmaCollection.from_yaml(rule_path.read_text(encoding="utf-8")), fmt)
                if isinstance(queries, str):
                    queries = [queries]
                if not queries:
                    raise ValueError("backend returned no query")
                header = (f"// {rule.title}\n// Sigma id: {rule.id} | level: {rule.level} | status: {rule.status}\n"
                          f"// Target: {desc}\n// Generated by tools/build_rules.py - UNTESTED, review field names before use.\n")
                if platform in ("splunk",):
                    header = header.replace("// ", "``` ", 1).replace("\n// ", "\n``` ")
                    header = "\n".join(l + " ```" if l.startswith("```") else l for l in header.splitlines()) + "\n"
                if ext == "pq":
                    header += ("// WARNING: the PQ backend approximates 'endswith' with 'contains' (e.g. '/sh' also matches '/ssh').\n"
                               "// Prefer the .dv variant or tighten the patterns after baselining.\n")
                body = "\n\n".join(str(q) for q in queries)
                if platform == "crowdstrike":
                    # The LogScale backend renders Sigma keywords as /"text"/i, a regex that requires
                    # literal double quotes around the text. Raw log lines have none: drop them
                    # (escape regex metacharacters in the keyword).
                    body = re.sub(r'/"([^"/]*)"/i', lambda m: "/" + re.sub(r'([.*+?()\[\]{}|^$\\])', r'\\\1', m.group(1)) + "/i", body)
                (outdir / f"{rule_path.stem}.{ext}").write_text(header + body + "\n", encoding="utf-8")
                report.append(f"| {rule_path.stem} | {platform} | {ext} | ok |")
            except Exception as e:  # noqa: BLE001
                msg = str(e).replace("\n", " ")[:160]
                report.append(f"| {rule_path.stem} | {platform} | {ext} | not converted: {msg} |")
    (ROOT / "rules" / "BUILD_REPORT.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print("\n".join(report))
    return rc


if __name__ == "__main__":
    sys.exit(main())
